import { useEffect, useRef, useState } from 'react';
import type { AtlasController, AtlasFrame } from './atlas-types.js';
import type { SeedLegend } from './map-atlas-data.js';
import { mapData, mapParams } from './map-query.js';
import type { ServerView } from './telemetry.js';

export type FeatureKind = {
  key: string;
  name: string;
  category: string;
  color: string;
  cellMeters: number;
};
type Feature = { kind: string; x: number; y: number; z: number };
type Tile = { features: Feature[]; truncated: boolean };
const empty: Tile = { features: [], truncated: false };

// Features are generated by the game. Fetch one viewport tile at a time and reuse
// neighbouring tiles when panning. Only an explicitly selected feature starts work.
export function useFeatureLayer(
  server: ServerView,
  world: string,
  processRef: string,
  face: number,
  frame: AtlasFrame | undefined,
  legend: SeedLegend | undefined,
  kind: FeatureKind | undefined,
  scene: React.RefObject<AtlasController | null>,
  coverage: unknown,
) {
  const edge = legend?.faceEdgeMeters ?? 0;
  const z =
    edge && kind
      ? Math.max(0, Math.ceil(Math.log2(edge / Math.min(2048, 64 * kind.cellMeters))))
      : 0;
  const side = edge / 2 ** z;
  const index = (m: number) => Math.min(2 ** z - 1, Math.max(0, Math.floor(m / side)));
  const b = frame?.bounds;
  const i0 = b && side ? index(b.i0 * 16) : 0,
    i1 = b && side ? index((b.i1 + 1) * 16 - 0.001) : 0;
  const j0 = b && side ? index(b.j0 * 16) : 0,
    j1 = b && side ? index((b.j1 + 1) * 16 - 0.001) : 0;
  const wide = !!kind && (!legend || z > legend.maxZoom || (i1 - i0 + 1) * (j1 - j0 + 1) > 12);
  const key = kind?.key;
  const scope = JSON.stringify([server.viewerScope, server.serverId, world, processRef, face, key]);
  const [attempt, retry] = useState(0);
  const windowKey = JSON.stringify([scope, i0, i1, j0, j1, z, attempt]);
  const [result, setResult] = useState<{ windowKey: string; tile: Tile; error?: unknown }>();
  const cache = useRef(new Map<string, Tile>());
  const cachedScope = useRef(scope);
  useEffect(() => {
    if (cachedScope.current !== scope) {
      cache.current.clear();
      cachedScope.current = scope;
    }
  }, [scope]);
  const serverRef = useRef(server);
  serverRef.current = server;
  const active = !!b && b.i0 * 16 < edge && b.j0 * 16 < edge && !!key && !wide;
  useEffect(() => {
    if (!active || !key) return;
    const abort = new AbortController();
    const tiles: Tile[] = [];
    const missing: { id: string; x: number; y: number }[] = [];
    const publish = (error?: unknown) => {
      if (!abort.signal.aborted)
        setResult({
          windowKey,
          tile: {
            features: tiles.flatMap((t) => t.features),
            truncated: tiles.some((t) => t.truncated),
          },
          error,
        });
    };
    for (let y = j0; y <= j1; y++)
      for (let x = i0; x <= i1; x++) {
        const id = JSON.stringify([scope, z, x, y]);
        const hit = cache.current.get(id);
        if (hit) tiles.push(hit);
        else missing.push({ id, x, y });
      }
    publish();
    const timer = setTimeout(async () => {
      try {
        for (const { id, x, y } of missing) {
          // Cache the decision for a whole tile. Panning inside a partly explored
          // tile can expose new ground without changing the request coordinates.
          const bounds = {
            i0: Math.floor((x * side) / 16),
            j0: Math.floor((y * side) / 16),
            i1: Math.ceil(((x + 1) * side) / 16) - 1,
            j1: Math.ceil(((y + 1) * side) / 16) - 1,
          };
          if (coverage && scene.current && !scene.current.mayNeedSeed(bounds, x, y, side)) continue;
          const params = mapParams({ world, processRef, face, x, y, z, kind: key });
          const tile = await mapData<Tile>(
            serverRef.current,
            `/seed-features?${params}`,
            abort.signal,
          );
          if (abort.signal.aborted) return;
          cache.current.set(id, tile);
          if (cache.current.size > 48)
            cache.current.delete(cache.current.keys().next().value as string);
          tiles.push(tile);
          publish();
        }
      } catch (e) {
        publish(e);
      }
    }, 180);
    return () => {
      clearTimeout(timer);
      abort.abort();
    };
  }, [
    active,
    scope,
    windowKey,
    i0,
    i1,
    j0,
    j1,
    z,
    key,
    world,
    processRef,
    face,
    coverage,
    scene,
    side,
  ]);
  const current = active && result?.windowKey === windowKey ? result : undefined;
  return {
    tile: current?.tile ?? empty,
    error: current?.error,
    wide,
    retry: () => retry((v) => v + 1),
  };
}
